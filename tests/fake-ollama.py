#!/usr/bin/env python3
"""fake-ollama.py - Ollama-Ersatz für die Tests von ollamaskope.

Antwortet auf /api/version, /api/tags, /api/ps, /api/show, /api/create und
/api/delete. Kein echtes Modell, keine GPU - nur so viel Verhalten, dass die
Schreibwege des Werkzeugs prüfbar sind, ohne fremden Bestand anzufassen.

Der Ersatz lehnt wie Ollama 0.40.14 das rohe Feld `modelfile` ab
("neither 'from' or 'files' was specified"). Damit fällt auf, wenn das
Werkzeug wieder versuchen sollte, das Modelfile unzerlegt zu senden.
"""

from __future__ import annotations

import json
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from typing import Any

MODELLFILE = '''# Modelfile generated by "ollama show"
# To build a new Modelfile based on this, replace FROM with:
# FROM qwen-test:7b

FROM /usr/share/ollama/.ollama/models/blobs/sha256-aaa
FROM /usr/share/ollama/.ollama/models/blobs/sha256-bbb
PARAMETER num_ctx 32768
PARAMETER temperature 0.2
PARAMETER stop "<|ende|>"
SYSTEM """
Du bist ein Testmodell.
"""
TEMPLATE {{ .Prompt }}
RENDERER qwen3.5
'''


def _startmodelle() -> dict[str, dict[str, Any]]:
    return {
        "qwen-test:7b": {
            "name": "qwen-test:7b",
            "model": "qwen-test:7b",
            "modified_at": "2026-11-01T10:00:00Z",
            "size": 4_300_000_000,
            "digest": "aaa",
            "details": {
                "parent_model": "qwen-test-base",
                "family": "qwen3",
                "parameter_size": "7.6B",
                "quantization_level": "Q4_K_M",
            },
        },
        "klein:latest": {
            "name": "klein:latest",
            "model": "klein:latest",
            "modified_at": "2026-10-20T08:30:00Z",
            "size": 640_000_000,
            "digest": "bbb",
            "details": {"family": "llama", "parameter_size": "1.1B"},
        },
        # Aus der Registry geladen: kein Elternteil, also nur durch Ziehen ausrollbar.
        "registry:7b": {
            "name": "registry:7b",
            "model": "registry:7b",
            "modified_at": "2026-11-02T09:00:00Z",
            "size": 2_100_000_000,
            "digest": "ccc",
            "details": {"family": "qwen3", "parameter_size": "7B"},
        },
    }


class FakeOllama:
    """Zustand des Ersatzes; die Handler greifen darauf zu."""

    def __init__(self) -> None:
        self.reset()

    def reset(self) -> None:
        self.modelle = _startmodelle()
        self.erzeugt: list[dict[str, Any]] = []
        self.zieht: list[str] = []
        self.kopiert: list[tuple[str, str]] = []
        self.geloescht: list[str] = []
        self.ladeauftraege: list[dict[str, Any]] = []
        self.geladen = ["qwen-test:7b"]
        # Elternteil je Modell, wie Ollama es in details.parent_model führt.
        self.eltern = {
            "qwen-test:7b": "qwen-test-base.gguf",
            "klein:latest": "qwen-test:7b",
        }


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.0"
    fake: FakeOllama
    still = True

    def log_message(self, *args: Any) -> None:  # noqa: D401, A003
        if not self.still:
            super().log_message(*args)

    def _json(self, code: int, obj: Any) -> None:
        roh = (json.dumps(obj) + "\n").encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(roh)))
        self.end_headers()
        self.wfile.write(roh)

    def _lesen(self) -> dict[str, Any] | None:
        laenge = int(self.headers.get("Content-Length") or 0)
        roh = self.rfile.read(laenge) if laenge else b"{}"
        try:
            daten = json.loads(roh or b"{}")
        except json.JSONDecodeError:
            self._json(400, {"error": "kein JSON"})
            return None
        return daten if isinstance(daten, dict) else None

    def do_GET(self) -> None:  # noqa: N802
        if self.path.startswith("/api/version"):
            self._json(200, {"version": "9.9.9-fake"})
            return
        if self.path.startswith("/api/tags"):
            self._json(200, {"models": list(self.fake.modelle.values())})
            return
        if self.path.startswith("/api/ps"):
            self._json(
                200,
                {
                    "models": [
                        {"name": name, "expires_at": "2319-01-01T00:00:00Z"}
                        for name in self.fake.geladen
                    ]
                },
            )
            return
        self._json(404, {"error": "unbekannter Pfad"})

    def do_POST(self) -> None:  # noqa: N802
        daten = self._lesen()
        if daten is None:
            return
        if self.path.startswith("/api/show"):
            modell = daten.get("model")
            if modell not in self.fake.modelle:
                self._json(404, {"error": f"model '{modell}' not found"})
                return
            self._json(
                200,
                {
                    "modelfile": MODELLFILE,
                    "details": {"parent_model": self.fake.eltern.get(str(modell), "")},
                    "parameters": "num_ctx 32768\ntemperature 0.2",
                    "system": "Du bist ein Testmodell.",
                    "template": "{{ .Prompt }}",
                    "capabilities": ["completion"],
                },
            )
            return
        if self.path.startswith("/api/generate"):
            modell = daten.get("model")
            if modell not in self.fake.modelle:
                self._json(404, {"error": f"model '{modell}' not found"})
                return
            behalten = daten.get("keep_alive")
            self.fake.ladeauftraege.append({"model": modell, "keep_alive": behalten})
            if behalten == 0:
                if modell in self.fake.geladen:
                    self.fake.geladen.remove(modell)
                grund = "unload"
            else:
                if modell not in self.fake.geladen:
                    self.fake.geladen.append(modell)
                grund = "load"
            self._json(
                200, {"model": modell, "done": True, "done_reason": grund}
            )
            return
        if self.path.startswith("/api/pull"):
            self._ziehen(daten)
            return
        if self.path.startswith("/api/copy"):
            quelle = str(daten.get("source") or "")
            ziel = str(daten.get("destination") or "")
            if quelle not in self.fake.modelle:
                self._json(404, {"error": f"model '{quelle}' not found"})
                return
            self.fake.modelle[ziel] = {
                **self.fake.modelle[quelle],
                "name": ziel,
                "model": ziel,
            }
            self.fake.kopiert.append((quelle, ziel))
            self._json(200, {})
            return
        if self.path.startswith("/api/create"):
            self.fake.erzeugt.append(daten)
            if "modelfile" in daten:
                self._json(
                    400, {"error": "neither 'from' or 'files' was specified"}
                )
                return
            name = daten.get("model")
            if not daten.get("from") or not name:
                self._json(
                    400, {"error": "neither 'from' or 'files' was specified"}
                )
                return
            self.fake.modelle[name] = {
                "name": name,
                "model": name,
                "modified_at": "2026-11-16T00:00:00Z",
                "size": 1,
                "digest": "neu",
                "details": {"family": "qwen3"},
            }
            self.send_response(200)
            self.send_header("Content-Type", "application/x-ndjson")
            self.send_header("Connection", "close")
            self.end_headers()
            for zeile in (
                {"status": "reading model metadata"},
                {"status": "writing manifest"},
                {"status": "success"},
            ):
                self.wfile.write((json.dumps(zeile) + "\n").encode("utf-8"))
            self.close_connection = True
            return
        if self.path.startswith("/api/delete"):
            self._loeschen(daten)
            return
        self._json(404, {"error": "unbekannter Pfad"})

    def do_DELETE(self) -> None:  # noqa: N802
        daten = self._lesen()
        if daten is None:
            return
        if self.path.startswith("/api/delete"):
            self._loeschen(daten)
            return
        self._json(404, {"error": "unbekannter Pfad"})

    def _ziehen(self, daten: dict[str, Any]) -> None:
        """Wie ein Pull aus der Registry: Modell landet im Bestand."""
        name = str(daten.get("model") or "")
        self.fake.zieht.append(name)
        if name and name not in self.fake.modelle:
            self.fake.modelle[name] = {
                "name": name,
                "model": name,
                "modified_at": "2026-11-16T00:00:00Z",
                "size": 1,
                "digest": "gezogen",
                "details": {"family": "qwen3"},
            }
        self.send_response(200)
        self.send_header("Content-Type", "application/x-ndjson")
        self.send_header("Connection", "close")
        self.end_headers()
        for zeile in (
            {"status": "pulling manifest"},
            {"status": "downloading", "total": 1000, "completed": 250},
            {"status": "downloading", "total": 1000, "completed": 1000},
            {"status": "success"},
        ):
            self.wfile.write((json.dumps(zeile) + "\n").encode("utf-8"))
        self.close_connection = True

    def _loeschen(self, daten: dict[str, Any]) -> None:
        modell = daten.get("model")
        if modell not in self.fake.modelle:
            self._json(404, {"error": f"model '{modell}' not found"})
            return
        del self.fake.modelle[modell]
        self.fake.geloescht.append(modell)
        self._json(200, {})


def starten() -> tuple[FakeOllama, threading.Thread, ThreadingHTTPServer]:
    """Ersatz auf einem freien Port starten."""
    fake = FakeOllama()
    handler = type("FakeHandler", (Handler,), {"fake": fake})
    server = ThreadingHTTPServer(("127.0.0.1", 0), handler)
    server.fake = fake  # type: ignore[attr-defined]
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    return fake, thread, server


if __name__ == "__main__":
    fake, thread, server = starten()
    print(f"fake-ollama auf http://127.0.0.1:{server.server_address[1]}")
    try:
        thread.join()
    except KeyboardInterrupt:
        server.shutdown()
